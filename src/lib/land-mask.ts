/** Decoded lazily on first use so importing this module costs nothing at parse. */
let bytes: Uint8Array | null = null

function decode(): Uint8Array {
  if (bytes) return bytes
  const binary = atob(PACKED)
  const out = new Uint8Array((WIDTH * HEIGHT) / 8)
  for (let i = 0; i < out.length; i++) out[i] = binary.charCodeAt(i)
  bytes = out
  return out
}

/** Raw bit for one cell, with x wrapped and y clamped. */
function bit(x: number, y: number): number {
  const px = ((x % WIDTH) + WIDTH) % WIDTH
  const py = y < 0 ? 0 : y > HEIGHT - 1 ? HEIGHT - 1 : y
  const index = py * WIDTH + px
  const data = decode()
  return ((data[index >> 3] ?? 0) >> (7 - (index & 7))) & 1
}

/**
 * Land coverage at a geographic position, 0 (sea) to 1 (land).
 *
 * Bilinear across the four neighbouring cells, so a 1-degree mask still yields
 * sub-cell coastlines. Longitude wraps, because the antimeridian is not a
 * coastline.
 */
export function landCoverage(lon: number, lat: number): number {
  if (lat > 90 || lat < -90) return 0

  const gx = ((lon + 180) / 360) * (WIDTH - 1)
  const gy = ((90 - lat) / 180) * (HEIGHT - 1)

  const x0 = Math.floor(gx)
  const y0 = Math.floor(gy)
  const fx = gx - x0
  const fy = gy - y0

  const ya = y0 < 0 ? 0 : y0 > HEIGHT - 1 ? HEIGHT - 1 : y0
  const yb = y0 + 1 < 0 ? 0 : y0 + 1 > HEIGHT - 1 ? HEIGHT - 1 : y0 + 1

  const top = bit(x0, ya) * (1 - fx) + bit(x0 + 1, ya) * fx
  const bottom = bit(x0, yb) * (1 - fx) + bit(x0 + 1, yb) * fx
  return top * (1 - fy) + bottom * fy
}
